import { chromium } from "playwright";
import { sessionCookie } from "./session.mjs";
const browser = await chromium.launch();
const ctx = await browser.newContext({ storageState: { cookies: [sessionCookie()], origins: [] }, viewport: { width: 390, height: 844 }, locale: "pt-BR", timezoneId: "America/Sao_Paulo", isMobile: true, hasTouch: true });
const page = await ctx.newPage();
const problems = [];
page.on("pageerror", (e) => problems.push(e.message));
await page.goto("http://localhost:3000/dashboard", { waitUntil: "networkidle" });
await page.waitForTimeout(1400);
await page.getByRole("button", { name: "Abrir menu" }).click();
await page.waitForTimeout(900);
await page.screenshot({ path: "/home/user/qa/m-01-drawer.png" });
await page.keyboard.press("Escape");
await page.waitForTimeout(500);
await page.goto("http://localhost:3000/tasks", { waitUntil: "networkidle" });
await page.waitForTimeout(1400);
await page.screenshot({ path: "/home/user/qa/m-02-tasks.png" });
await page.goto("http://localhost:3000/analytics", { waitUntil: "networkidle" });
await page.waitForTimeout(1600);
await page.screenshot({ path: "/home/user/qa/m-03-analytics.png" });
await page.goto("http://localhost:3000/calendar", { waitUntil: "networkidle" });
await page.waitForTimeout(1400);
await page.screenshot({ path: "/home/user/qa/m-04-calendar.png" });
await browser.close();
console.log(problems.length ? "ERRORS: " + problems.join(" | ") : "mobile ok");
